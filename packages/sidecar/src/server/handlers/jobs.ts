/**
 * jobs.* handler — process-level scheduler API. Lives alongside the
 * other handlers/ entries but is registered last in methods.ts so its
 * `jobs` field on ServerRpcSurface is always populated by the time a
 * client can call it (initialize handshake gates non-init RPCs).
 *
 * The method names and wire shapes live in `@taco-ai/protocol`, so the
 * sidecar, the desktop and the contract table all read the same strings.
 * The schemas come from the contract table too, which is why no method
 * passes one here.
 */

import type {
    Actor,
    JobRunResult,
    JobsDeleteResult,
    JobsGetResult,
    JobsHistoryResult,
    JobsListResult,
    JobsWriteResult,
    Job as WireJob,
} from "@taco-ai/protocol";
import { JobAlreadyExistsError, JobsScopeError } from "../../lib/jobsErrors.ts";
import { BUILTIN_JOB_COMMANDS, parseMemoryDreamArgs } from "../../scheduler/builtinJobs.ts";
import { safeJobId } from "../../scheduler/jobId.ts";
import type { Job as SchedulerJob } from "../../scheduler/types.ts";
import { RpcHandlerError, registerMethod } from "../methodRegistry.ts";

/**
 * The actor that scopes this call, or undefined for an unscoped caller.
 *
 * The contract schema validates the actor (an `im` triple or an `ide`
 * workspace), so the value that reaches the handler is already well-formed;
 * a malformed one never gets here. The presence of an actor is what gates
 * scope enforcement in JobsController.
 */
function extractActor(params: { actor?: Actor }): Actor | undefined {
    return params.actor;
}

export function registerJobsHandlers(): void {
    registerMethod("jobsList", false, async ({ server, params }): Promise<JobsListResult> => {
        const actor = extractActor(params);
        const jobs = server.jobs ? await server.jobs.list(actor) : [];
        return { jobs };
    });

    registerMethod("jobsGet", false, async ({ server, params }): Promise<JobsGetResult> => {
        const id = params.id;
        safeJobId(id);
        const actor = extractActor(params);
        const job = server.jobs ? await server.jobs.get(id, actor) : null;
        return { job };
    });

    registerMethod("jobsCreate", false, async ({ server, params }): Promise<JobsWriteResult> => {
        if (!server.jobs) throw new RpcHandlerError("not_ready", "scheduler not running");
        // The daemon mints the id, so a caller-supplied one is blanked here.
        const job = toSchedulerJob(assertJobSemantics({ ...params.job, id: "" }));
        // Create IDs are generated by the daemon. A supplied id is
        // ignored by JobsController rather than becoming an overwrite key.
        const actor = extractActor(params);
        try {
            const saved = await server.jobs.create(job, actor);
            return { job: saved };
        } catch (err) {
            throw scopeErrorToRpc(err);
        }
    });

    registerMethod("jobsUpdate", false, async ({ server, params }): Promise<JobsWriteResult> => {
        if (!server.jobs) throw new RpcHandlerError("not_ready", "scheduler not running");
        const job = toSchedulerJob(assertJobSemantics(params.job));
        safeJobId(job.id);
        const actor = extractActor(params);
        try {
            const saved = await server.jobs.update(job, actor);
            return { job: saved };
        } catch (err) {
            throw scopeErrorToRpc(err);
        }
    });

    registerMethod("jobsDelete", false, async ({ server, params }): Promise<JobsDeleteResult> => {
        if (!server.jobs) throw new RpcHandlerError("not_ready", "scheduler not running");
        const id = params.id;
        safeJobId(id);
        const actor = extractActor(params);
        let existed = false;
        try {
            existed = (await server.jobs.get(id, actor)) !== null;
            await server.jobs.delete(id, actor);
        } catch (err) {
            throw scopeErrorToRpc(err);
        }
        return { deleted: existed };
    });

    registerMethod("jobsRunNow", false, async ({ server, params }): Promise<JobRunResult> => {
        if (!server.jobs) throw new RpcHandlerError("not_ready", "scheduler not running");
        const id = params.id;
        safeJobId(id);
        const actor = extractActor(params);
        try {
            return await server.jobs.runNow(id, actor);
        } catch (err) {
            throw scopeErrorToRpc(err);
        }
    });

    registerMethod("jobsHistory", false, async ({ server, params }): Promise<JobsHistoryResult> => {
        const id = params.id;
        safeJobId(id);
        const actor = extractActor(params);
        const history = server.jobs ? await server.jobs.history(id, actor) : null;
        return { history };
    });
}

/**
 * Converts a wire job into the scheduler's internal shape.
 *
 * The wire type leaves `history` optional because the desktop never sends
 * it; the scheduler always has one, seeding `[]` when the job is created.
 */
function toSchedulerJob(job: WireJob): SchedulerJob {
    return { ...job, history: job.history ?? [] };
}

/**
 * The semantic checks a shape cannot express.
 *
 * The envelope is validated by the contract schema before the handler runs,
 * so only the rules the schema cannot state live here: which commands the
 * scheduler accepts, and what an `agent.invoke` body must carry.
 */
function assertJobSemantics(job: WireJob): WireJob {
    // Built-in jobs (builtinJobs.ts) carry a native command and handler-
    // specific args instead of a workspace + prompt. Whether the caller may
    // write one at all is the controller's call; here only the shape is checked.
    if (job.builtin === true) {
        if (!BUILTIN_JOB_COMMANDS.has(job.command)) {
            throw new RpcHandlerError(
                "invalid_params",
                `job.command ${JSON.stringify(job.command)} is not a built-in command`,
            );
        }
        const parsed = parseMemoryDreamArgs(job.args);
        if (!parsed.ok) throw new RpcHandlerError("invalid_params", `job.${parsed.error}`);
        return { ...job, args: { ...parsed.args } };
    }
    // The scheduler dispatcher only knows `agent.invoke` today — every other
    // command would land in `dispatcher.createJobDispatcher` and throw
    // `unsupported scheduled command`. Refuse here so the failure is
    // actionable (a clear invalid_params) instead of a recurring err entry
    // in the job's history. When a real second command shows up, add it to
    // the set AND wire the dispatcher to handle it.
    // A client from before built-in jobs edits one without echoing
    // `builtin: true`; say so instead of the agent.invoke message below.
    if (BUILTIN_JOB_COMMANDS.has(job.command)) {
        throw new RpcHandlerError(
            "invalid_params",
            `job.command ${JSON.stringify(job.command)} belongs to a built-in job; update the client to edit it`,
        );
    }
    if (job.command !== "agent.invoke") {
        throw new RpcHandlerError(
            "invalid_params",
            `job.command must be "agent.invoke" ` +
                "(scheduler dispatches to a fresh agent session; " +
                "place shell-style commands in args.prompt and let the agent " +
                `route them through tools). Got: ${JSON.stringify(job.command)}`,
        );
    }
    // `agent.invoke` needs a workspace and a prompt. The args bag is
    // free-form on the wire, so the schema cannot require them.
    const args = job.args as Record<string, unknown>;
    if (typeof args.workspace !== "string" || args.workspace.length === 0) {
        throw new RpcHandlerError(
            "invalid_params",
            "job.args.workspace is required and must be a non-empty string",
        );
    }
    // Same allowlist argument: every other shape falls through to a
    // no-context agent session that has nothing to do, and the operator only
    // notices via silent history entries.
    if (typeof args.prompt !== "string" || args.prompt.length === 0) {
        throw new RpcHandlerError(
            "invalid_params",
            "job.args.prompt is required and must be a non-empty string",
        );
    }
    return job;
}

/** Map JobsController's scope errors to wire codes. Out-of-scope reads
 *  are mapped to `not_found` (never leak existence); writes are
 *  `forbidden` so the caller can distinguish "missing" from "denied". */
function scopeErrorToRpc(err: unknown): RpcHandlerError {
    if (err instanceof JobsScopeError) {
        return new RpcHandlerError(err.code, err.message);
    }
    // Duplicate-id create gets a dedicated code — without this branch it
    // would fall through to normalizeError and surface as a redacted
    // "[upstream] internal" error the caller can't branch on.
    if (err instanceof JobAlreadyExistsError) {
        return new RpcHandlerError("conflict", err.message);
    }
    // Re-throw unknown errors so the existing try/catch chain (or the
    // handler wrapper) maps them to internal_error.
    throw err;
}
