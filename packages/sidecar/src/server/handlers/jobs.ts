/**
 * jobs.* handler — process-level scheduler API. Lives alongside the
 * other handlers/ entries but is registered last in methods.ts so its
 * `jobs` field on ServerRpcSurface is always populated by the time a
 * client can call it (initialize handshake gates non-init RPCs).
 *
 * The method names and wire shapes live in `@taco-ai/protocol`, so the
 * sidecar, the desktop and the contract table all read the same strings.
 * The schemas come from the contract table too, which is why no method
 * passes one here.
 */

import type {
    Actor,
    JobRunResult,
    JobsDeleteResult,
    JobsGetResult,
    JobsHistoryResult,
    JobsListResult,
    JobsWriteResult,
    SessionStrategy,
    Job as WireJob,
} from "@taco-ai/protocol";
import { JobAlreadyExistsError, JobsScopeError } from "../../lib/jobsErrors.ts";
import { BUILTIN_JOB_COMMANDS, parseMemoryDreamArgs } from "../../scheduler/builtinJobs.ts";
import { safeJobId } from "../../scheduler/jobId.ts";
import type { Job as SchedulerJob } from "../../scheduler/types.ts";
import { RpcHandlerError, registerMethod } from "../methodRegistry.ts";

/** Extract an optional `Actor` from params; returns undefined when absent
 *  or malformed (legacy callers / admin tooling). The presence of a
 *  well-formed actor is what gates scope enforcement in JobsController. */
function extractActor(params: unknown): Actor | undefined {
    if (typeof params !== "object" || params === null) return undefined;
    const raw = (params as Record<string, unknown>).actor;
    if (typeof raw !== "object" || raw === null) return undefined;
    const obj = raw as Record<string, unknown>;
    if (obj.kind === "im") {
        if (
            typeof obj.channelId === "string" &&
            typeof obj.peerId === "string" &&
            typeof obj.chatId === "string"
        ) {
            return { kind: "im", channelId: obj.channelId, peerId: obj.peerId, chatId: obj.chatId };
        }
        return undefined;
    }
    if (obj.kind === "ide" && typeof obj.workspace === "string") {
        return { kind: "ide", workspace: obj.workspace };
    }
    return undefined;
}

export function registerJobsHandlers(): void {
    registerMethod("jobsList", false, async ({ server, params }): Promise<JobsListResult> => {
        const actor = extractActor(params);
        const jobs = server.jobs ? await server.jobs.list(actor) : [];
        return { jobs };
    });

    registerMethod("jobsGet", false, async ({ server, params }): Promise<JobsGetResult> => {
        const id = expectString(params, "id");
        safeJobId(id);
        const actor = extractActor(params);
        const job = server.jobs ? await server.jobs.get(id, actor) : null;
        return { job };
    });

    registerMethod("jobsCreate", false, async ({ server, params }): Promise<JobsWriteResult> => {
        if (!server.jobs) throw new RpcHandlerError("not_ready", "scheduler not running");
        const job = toSchedulerJob({ ...assertJob(params, "job"), id: "" });
        // Create IDs are generated by the daemon. A supplied id is
        // ignored by JobsController rather than becoming an overwrite key.
        const actor = extractActor(params);
        try {
            const saved = await server.jobs.create(job, actor);
            return { job: saved };
        } catch (err) {
            throw scopeErrorToRpc(err);
        }
    });

    registerMethod("jobsUpdate", false, async ({ server, params }): Promise<JobsWriteResult> => {
        if (!server.jobs) throw new RpcHandlerError("not_ready", "scheduler not running");
        const job = toSchedulerJob(assertJob(params, "job", true));
        safeJobId(job.id);
        const actor = extractActor(params);
        try {
            const saved = await server.jobs.update(job, actor);
            return { job: saved };
        } catch (err) {
            throw scopeErrorToRpc(err);
        }
    });

    registerMethod("jobsDelete", false, async ({ server, params }): Promise<JobsDeleteResult> => {
        if (!server.jobs) throw new RpcHandlerError("not_ready", "scheduler not running");
        const id = expectString(params, "id");
        safeJobId(id);
        const actor = extractActor(params);
        let existed = false;
        try {
            existed = (await server.jobs.get(id, actor)) !== null;
            await server.jobs.delete(id, actor);
        } catch (err) {
            throw scopeErrorToRpc(err);
        }
        return { deleted: existed };
    });

    registerMethod("jobsRunNow", false, async ({ server, params }): Promise<JobRunResult> => {
        if (!server.jobs) throw new RpcHandlerError("not_ready", "scheduler not running");
        const id = expectString(params, "id");
        safeJobId(id);
        const actor = extractActor(params);
        try {
            return await server.jobs.runNow(id, actor);
        } catch (err) {
            throw scopeErrorToRpc(err);
        }
    });

    registerMethod("jobsHistory", false, async ({ server, params }): Promise<JobsHistoryResult> => {
        const id = expectString(params, "id");
        safeJobId(id);
        const actor = extractActor(params);
        const history = server.jobs ? await server.jobs.history(id, actor) : null;
        return { history };
    });
}

/**
 * Converts a wire job into the scheduler's internal shape.
 *
 * The wire type leaves `history` optional because the desktop never sends
 * it; the scheduler always has one, seeding `[]` when the job is created.
 */
function toSchedulerJob(job: WireJob): SchedulerJob {
    return { ...job, history: job.history ?? [] };
}

function expectString(params: unknown, field: string): string {
    if (typeof params !== "object" || params === null) {
        throw new RpcHandlerError(
            "invalid_params",
            `params must be an object (got ${typeof params})`,
        );
    }
    const value = (params as Record<string, unknown>)[field];
    if (typeof value !== "string" || value.length === 0) {
        throw new RpcHandlerError("invalid_params", `${field} must be a non-empty string`);
    }
    return value;
}

function assertJob(params: unknown, field: string, requireId = false): WireJob {
    if (typeof params !== "object" || params === null) {
        throw new RpcHandlerError(
            "invalid_params",
            `params must be an object (got ${typeof params})`,
        );
    }
    const candidate = (params as Record<string, unknown>)[field];
    if (typeof candidate !== "object" || candidate === null) {
        throw new RpcHandlerError("invalid_params", `${field} must be a job object`);
    }
    const obj = candidate as Record<string, unknown>;
    if (requireId && (typeof obj.id !== "string" || obj.id.length === 0)) {
        throw new RpcHandlerError("invalid_params", `${field}.id must be a non-empty string`);
    }
    if (typeof obj.name !== "string") {
        throw new RpcHandlerError("invalid_params", `${field}.name must be a string`);
    }
    if (!isScheduleSpec(obj.schedule)) {
        throw new RpcHandlerError("invalid_params", `${field}.schedule is malformed`);
    }
    if (typeof obj.command !== "string") {
        throw new RpcHandlerError("invalid_params", `${field}.command must be a string`);
    }
    // Built-in jobs (builtinJobs.ts) carry a native command and handler-
    // specific args instead of a workspace + prompt. Whether the caller may
    // write one at all is the controller's call; here only the shape is checked.
    if (obj.builtin === true) {
        if (!BUILTIN_JOB_COMMANDS.has(obj.command)) {
            throw new RpcHandlerError(
                "invalid_params",
                `${field}.command ${JSON.stringify(obj.command)} is not a built-in command`,
            );
        }
        if (typeof obj.args !== "object" || obj.args === null) {
            throw new RpcHandlerError("invalid_params", `${field}.args must be an object`);
        }
        const parsed = parseMemoryDreamArgs(obj.args as Record<string, unknown>);
        if (!parsed.ok) throw new RpcHandlerError("invalid_params", `${field}.${parsed.error}`);
        if (typeof obj.enabled !== "boolean") {
            throw new RpcHandlerError("invalid_params", `${field}.enabled must be a boolean`);
        }
        return { ...(obj as unknown as WireJob), args: { ...parsed.args } };
    }
    // The scheduler dispatcher only knows `agent.invoke` today — every other
    // command would land in `dispatcher.createJobDispatcher` and throw
    // `unsupported scheduled command`. Refuse here so the failure is
    // actionable (a clear invalid_params) instead of a recurring err entry
    // in the job's history. When a real second command shows up, add it to
    // the set AND wire the dispatcher to handle it.
    // A client from before built-in jobs edits one without echoing
    // `builtin: true`; say so instead of the agent.invoke message below.
    if (typeof obj.command === "string" && BUILTIN_JOB_COMMANDS.has(obj.command)) {
        throw new RpcHandlerError(
            "invalid_params",
            `${field}.command ${JSON.stringify(obj.command)} belongs to a built-in job; update the client to edit it`,
        );
    }
    if (obj.command !== "agent.invoke") {
        throw new RpcHandlerError(
            "invalid_params",
            `${field}.command must be "agent.invoke" ` +
                "(scheduler dispatches to a fresh agent session; " +
                "place shell-style commands in args.prompt and let the agent " +
                `route them through tools). Got: ${JSON.stringify(obj.command)}`,
        );
    }
    if (typeof obj.args !== "object" || obj.args === null) {
        throw new RpcHandlerError("invalid_params", `${field}.args must be an object`);
    }
    const argsObj = obj.args as Record<string, unknown>;
    if (typeof argsObj.workspace !== "string" || argsObj.workspace.length === 0) {
        throw new RpcHandlerError(
            "invalid_params",
            `${field}.args.workspace is required and must be a non-empty string`,
        );
    }
    // `agent.invoke` requires a prompt. Same allowlist argument: every other
    // shape falls through to a no-context agent session that has nothing to
    // do, and the operator only notices via silent history entries.
    if (typeof argsObj.prompt !== "string" || argsObj.prompt.length === 0) {
        throw new RpcHandlerError(
            "invalid_params",
            `${field}.args.prompt is required and must be a non-empty string`,
        );
    }
    if (typeof obj.enabled !== "boolean") {
        throw new RpcHandlerError("invalid_params", `${field}.enabled must be a boolean`);
    }
    if (typeof obj.run_on_startup !== "boolean") {
        throw new RpcHandlerError("invalid_params", `${field}.run_on_startup must be a boolean`);
    }
    // Caps are optional, but a malformed one must not reach the store: a
    // fractional or negative `max_runs` would make `run_count >= max_runs`
    // either never or immediately true, retiring the job at the wrong time.
    if (
        obj.max_runs !== undefined &&
        (typeof obj.max_runs !== "number" || !Number.isInteger(obj.max_runs) || obj.max_runs < 1)
    ) {
        throw new RpcHandlerError(
            "invalid_params",
            `${field}.max_runs must be an integer >= 1 when present`,
        );
    }
    if (
        obj.max_consecutive_failures !== undefined &&
        (typeof obj.max_consecutive_failures !== "number" ||
            !Number.isInteger(obj.max_consecutive_failures) ||
            obj.max_consecutive_failures < 0)
    ) {
        throw new RpcHandlerError(
            "invalid_params",
            `${field}.max_consecutive_failures must be an integer >= 0 when present ` +
                "(0 disables the circuit breaker)",
        );
    }
    if (obj.sessionStrategy !== undefined && !isSessionStrategy(obj.sessionStrategy)) {
        throw new RpcHandlerError(
            "invalid_params",
            `${field}.sessionStrategy must be "new" | "reuse" | "pin"`,
        );
    }
    return { ...obj, id: typeof obj.id === "string" ? obj.id : "" } as unknown as WireJob;
}

function isScheduleSpec(value: unknown): boolean {
    if (typeof value !== "object" || value === null) return false;
    const s = value as Record<string, unknown>;
    if (s.kind === "cron") {
        return (
            typeof s.expr === "string" &&
            s.expr.length > 0 &&
            (s.tz === undefined || typeof s.tz === "string")
        );
    }
    if (s.kind === "interval") {
        return typeof s.ms === "number" && Number.isInteger(s.ms) && s.ms > 0;
    }
    return false;
}

function isSessionStrategy(value: unknown): value is SessionStrategy {
    return value === "new" || value === "reuse" || value === "pin";
}

/** Map JobsController's scope errors to wire codes. Out-of-scope reads
 *  are mapped to `not_found` (never leak existence); writes are
 *  `forbidden` so the caller can distinguish "missing" from "denied". */
function scopeErrorToRpc(err: unknown): RpcHandlerError {
    if (err instanceof JobsScopeError) {
        return new RpcHandlerError(err.code, err.message);
    }
    // Duplicate-id create gets a dedicated code — without this branch it
    // would fall through to normalizeError and surface as a redacted
    // "[upstream] internal" error the caller can't branch on.
    if (err instanceof JobAlreadyExistsError) {
        return new RpcHandlerError("conflict", err.message);
    }
    // Re-throw unknown errors so the existing try/catch chain (or the
    // handler wrapper) maps them to internal_error.
    throw err;
}
